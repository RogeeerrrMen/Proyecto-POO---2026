BEGIN;

CREATE TABLE IF NOT EXISTS public.planes_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id BIGINT NOT NULL UNIQUE REFERENCES public.pagos(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('CUOTAS', 'DIVIDIDO')),
    saldo_inicial NUMERIC(14, 2) NOT NULL CHECK (saldo_inicial > 0),
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.partes_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES public.planes_pago(id),
    numero INTEGER NOT NULL CHECK (numero > 0),
    persona VARCHAR(120),
    fecha_vencimiento DATE,
    monto NUMERIC(14, 2) NOT NULL CHECK (monto > 0),
    total_abonado NUMERIC(14, 2) NOT NULL DEFAULT 0,
    CONSTRAINT uk_parte_plan_numero UNIQUE (plan_id, numero),
    CONSTRAINT chk_parte_abonado CHECK (total_abonado >= 0 AND total_abonado <= monto)
);

ALTER TABLE public.abonos
    ADD COLUMN IF NOT EXISTS parte_pago_id BIGINT REFERENCES public.partes_pago(id);

CREATE INDEX IF NOT EXISTS idx_abonos_parte_pago ON public.abonos(parte_pago_id);

COMMIT;
